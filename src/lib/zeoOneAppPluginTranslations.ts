export function getZeoOneAppPluginText(key: string, lang = "en"): string {
	const normalized = lang.toLowerCase();
	const language = normalized === "zh" || normalized === "zh-hans" ? "zh-cn" : normalized;
	const valid = (value: string | undefined): value is string => !!value && !value.includes("###");
	const selected = translations[language]?.[key];
	if (valid(selected)) return selected;
	const english = translations.en[key];
	if (valid(english)) return english;
	return translations["zh-cn"][key] ?? key;
}

export function getZeoOneAppPluginName(key: string): ioBroker.StringOrTranslated {
	const result: Record<string, string> = {};
	for (const lang of [...Object.keys(translations), "nl"]) result[lang] = getZeoOneAppPluginText(key, lang);
	return result as ioBroker.StringOrTranslated;
}
